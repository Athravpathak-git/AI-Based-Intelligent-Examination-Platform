def get_question_translations(question_text: Optional[str]) -> Optional[Dict[str, str]]:
    """Retrieve full 7-language translation dictionary for question text."""
    if not question_text:
        return None
    clean = question_text.strip()

    # 1. Exact match
    if clean in QUESTION_TRANSLATIONS:
        return QUESTION_TRANSLATIONS[clean]

    # 2. Dynamic pattern matching
    matched = match_dynamic_question(clean)
    if matched:
        return matched

    # 3. Substring match fallback
    for key, trans in QUESTION_TRANSLATIONS.items():
        if key in clean or clean in key:
            return trans

    return None

def get_option_translations(option_text: Optional[str]) -> Optional[Dict[str, str]]:
    """Retrieve full 7-language translation dictionary for option text."""
    if not option_text:
        return None
    clean = option_text.strip()

    # 1. Exact match
    if clean in OPTION_TRANSLATIONS:
        return OPTION_TRANSLATIONS[clean]

    # 2. Dynamic pattern matching
    matched = match_dynamic_option(clean)
    if matched:
        return matched

    return None
