# ============================================================================
def match_dynamic_option(text: str) -> Optional[Dict[str, str]]:
    clean = text.strip()

    # Numeric Joules
    m = re.match(r"([0-9.]+) Joules", clean)
    if m:
        val = m.group(1)
        return {
            "en": f"{val} Joules",
            "mr": f"{val} ज्यूल",
            "hi": f"{val} जूल",
            "te": f"{val} జూల్స్",
            "ta": f"{val} ஜூல்ஸ்",
            "ml": f"{val} ജൂൾസ്",
            "kn": f"{val} ಜೂಲ್‌ಗಳು"
        }

    # Degrees
    m = re.match(r"([0-9.]+) degrees", clean)
    if m:
        val = m.group(1)
        return {
            "en": f"{val} degrees",
            "mr": f"{val} अंश (degrees)",
            "hi": f"{val} डिग्री",
            "te": f"{val} డిగ్రీలు",
            "ta": f"{val} பாகை (degrees)",
            "ml": f"{val} ഡിഗ്രി",
            "kn": f"{val} ಡಿಗ್ರಿ"
        }

    # Distance direction
    m = re.match(r"([0-9.]+) km (Northeast|North|East)", clean)
    if m:
        dist, dir_name = m.groups()
        dir_maps = {
            "Northeast": {"mr": "ईशान्य", "hi": "उत्तर-पूर्व", "te": "ఈశాన్యం", "ta": "வடகிழக்கு", "ml": "വടക്കുകിഴക്ക്", "kn": "ಈಶಾನ್ಯ"},
            "North": {"mr": "उत्तर", "hi": "उत्तर", "te": "ఉత్తరం", "ta": "வடக்கு", "ml": "വടക്ക്", "kn": "ಉತ್ತರ"},
            "East": {"mr": "पूर्व", "hi": "पूर्व", "te": "తూర్పు", "ta": "கிழக்கு", "ml": "കിഴക്ക്", "kn": "ಪೂರ್ವ"}
        }
        d = dir_maps.get(dir_name, {"mr": dir_name, "hi": dir_name, "te": dir_name, "ta": dir_name, "ml": dir_name, "kn": dir_name})
        return {
            "en": clean,
            "mr": f"{dist} किमी {d['mr']}",
            "hi": f"{dist} किमी {d['hi']}",
            "te": f"{dist} కి.మీ {d['te']}",
            "ta": f"{dist} கி.மீ {d['ta']}",
            "ml": f"{dist} കി.മീ {d['ml']}",
            "kn": f"{dist} ಕಿಮೀ {d['kn']}"
        }

    # Huckel yes n = ...
    m = re.match(r"Yes, corresponds to n = (\d+)\.", clean)
    if m:
        n = m.group(1)
        return {
            "en": clean,
            "mr": f"होय, हे n = {n} ला अनुरूप आहे.",
            "hi": f"हाँ, यह n = {n} से मेल खाता है।",
            "te": f"అవును, ఇది n = {n} కి అనుగుణంగా ఉంటుంది.",
            "ta": f"ஆம், n = {n} உடன் ஒத்துள்ளது.",
            "ml": f"അതെ, n = {n} എന്നതിന് തുല്യമാണ്.",
            "kn": f"ಹೌದು, ಇದು n = {n} ಗೆ ಅನುರೂಪವಾಗಿದೆ."
        }

    return None

